import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import {adminBikeRanking} from './lib/admin-bike-ranking.mjs';
const db=new DatabaseSync(':memory:');
db.exec(`CREATE TABLE members(id INTEGER,evo_member_id INTEGER,presencas_legadas_bike INTEGER,first_name TEXT,last_name TEXT);
CREATE TABLE evo_member_master(unit TEXT,evo_member_id TEXT,personal_json TEXT);
CREATE TABLE evo_member_attendance(unit TEXT,evo_member_id TEXT,attendance_date TEXT);
INSERT INTO members VALUES(1,101,10,'Ana','Teste'),(2,102,12,'Bia','Teste'),(3,999,0,'Gym','Only');
INSERT INTO evo_member_master VALUES('bike','101','{"document":"12345678901"}'),('bike','102','{}'),('gym','999','{}'),('bike','103','{"firstName":"Caio","lastName":"Espelho"}');
INSERT INTO evo_member_attendance VALUES('bike','101','2026-10-17'),('bike','101','2026-10-17'),('gym','101','2026-10-17'),('gym','999','2026-10-17');`);
const binding={prepare(sql){return {bind(...params){return {sql,params}}}},async batch(stmts){return stmts.map(s=>({results:db.prepare(s.sql).all(...s.params)}))}};
const run=q=>adminBikeRanking(binding,new URLSearchParams(q));
let r=await run('');assert.equal(r.total,3);assert.equal(r.summary.stars,24);assert.equal(r.rows[0].actual,2);assert.equal(r.rows[0].position,1);assert.equal(r.rows[1].position,1);assert.equal(r.rows[0].progress.currentMilestone,12);assert.equal(r.rows[0].progress.nextMilestone,24);
r=await run('q=123.456.789-01');assert.equal(r.total,1);assert.equal(r.rows[0].name,'Ana Teste');
r=await run('q=Bia');assert.equal(r.rows[0].position,1);
r=await run('min=13');assert.equal(r.total,0);
for(let i=0;i<25;i++)db.prepare('INSERT INTO evo_member_master VALUES(?,?,?)').run('bike',String(200+i),JSON.stringify({firstName:'Aluno '+i}));
r=await run('page=2');assert.equal(r.rows.length,10);assert.equal(r.total,28);
r=await run('order=az');assert.equal(r.rows[0].name,'Aluno 0');
db.prepare('UPDATE members SET presencas_legadas_bike=21 WHERE id=1').run();
r=await run('q=Ana');assert.equal(r.summary.near,1);assert.equal(r.upcoming[0].remaining,1);
assert.equal(Object.hasOwn(r.rows[0],'cpf'),false);
console.log('Ranking: same-day classes, Gym isolation, ties, CPF, filters, pagination and milestones OK');
